def strip_visuals(html: str) -> str:
    for start, end in [
        ("<!-- DIH:GALLERY -->", "<!-- /DIH:GALLERY -->"),
        ("<!-- DIH:AMBIENT -->", "<!-- /DIH:AMBIENT -->"),
    ]:
        html = re.sub(re.escape(start) + r".*?" + re.escape(end) + r"\n?", "", html, flags=re.S)
    return html


def process_index(path: Path) -> bool:
    """Homepage: keep its hand-authored head and chrome, add the visual layer."""
    rel = path.relative_to(ROOT)
    html = path.read_text(encoding="utf-8")
    # Homepage v2 owns its full layout (banner, tabs, interest board); the
    # builder must not re-insert the gallery or reorder sections.
    if 'data-home="v2"' in html:
        return False
    cleaned = strip_visuals(html)
    if 'data-page="home"' not in cleaned:
        cleaned = re.sub(r"<body([^>]*)>", r'<body\1 data-page="home">', cleaned, count=1, flags=re.I)
    body_open = re.search(r"<body[^>]*>", cleaned, re.I)
    if not body_open:
        return False
    cleaned = cleaned[: body_open.end()] + "\n" + ambient_html(str(rel)) + cleaned[body_open.end():]
    marker = "<!-- Daily insight -->"
    if marker in cleaned:
        # Keep the homepage gallery inside the page flow, not after the content.
        cleaned = cleaned.replace(marker, gallery_html(str(rel), "home") + "\n" + marker, 1)
    else:
        marker = "<!-- DIH:FOOTER -->"
    if "dih-gallery" not in cleaned and marker in cleaned:
        cleaned = cleaned.replace(marker, gallery_html(str(rel), "home") + "\n" + marker, 1)
    elif "dih-gallery" not in cleaned:
        idx = cleaned.rfind('<footer class="dih-footer"')
        if idx == -1:
            return False
        cleaned = cleaned[:idx] + gallery_html(str(rel), "home") + "\n" + cleaned[idx:]
    if cleaned != html:
        path.write_text(cleaned, encoding="utf-8")
        return True
    return False



def escape_attr(text: str) -> str:
    return (text or "").replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")


def update_head(html: str, rel: Path, meta: dict) -> str:
    html = strip_injected(html)
    title = escape_attr(meta["title"])
    desc = escape_attr(clean(meta["desc"]))

    if re.search(r"<title>.*?</title>", html, re.I | re.S):
        html = re.sub(r"<title>.*?</title>", f"<title>{title}</title>", html, count=1, flags=re.I | re.S)
    else:
        html = re.sub(r"(<head[^>]*>)", r"\1\n<title>" + title + "</title>", html, count=1, flags=re.I)

    if re.search(r'<meta\s+name="description"', html, re.I):
        html = re.sub(r'<meta\s+name="description"[^>]*>', f'<meta name="description" content="{desc}">', html, count=1, flags=re.I)
    else:
        html = re.sub(r"(<meta\s+charset[^>]*>)", r'\1\n<meta name="description" content="' + desc + '">', html, count=1, flags=re.I)

    # Remove stale social / canonical / icon tags; the shared block replaces them.
    html = re.sub(r'\n?<link\s+rel="canonical"[^>]*>', "", html, flags=re.I)
    html = re.sub(r'\n?<meta\s+(?:property|name)="(?:og|twitter):[^"]*"[^>]*>', "", html, flags=re.I)
    html = re.sub(r'\n?<link\s+rel="(?:icon|apple-touch-icon|shortcut icon|manifest)"[^>]*>', "", html, flags=re.I)
    html = re.sub(r'\n?<meta\s+name="theme-color"[^>]*>', "", html, flags=re.I)
    html = re.sub(r'\n?<meta\s+name="robots"[^>]*>', "", html, flags=re.I)
    html = re.sub(r'\n?<meta\s+name="author"[^>]*>', "", html, flags=re.I)
    html = re.sub(r'\n?<meta\s+name="keywords"[^>]*>', "", html, flags=re.I)

    html = html.replace("</head>", seo_block(rel, meta, html) + "\n</head>", 1)
    return html


def update_body(html: str, rel: Path, meta: dict) -> str:
    kind = meta.get("kind", "blog")
    page = "tool" if kind == "tool" else ("games" if kind == "games" else ("subscribe" if kind == "subscribe" else ("coincompass" if kind == "coincompass" else "")))
    attr = f' data-page="{page}"' if page else ""

    m = re.search(r"<body([^>]*)>", html, re.I)
    if m:
        attrs = m.group(1)
        attrs = re.sub(r'\sdata-page="[^"]*"', "", attrs)
        html = html[: m.start()] + f"<body{attrs}{attr}>" + html[m.end():]
    else:
        return html

    if "data-dih" not in html[:600]:
        html = re.sub(r"<html([^>]*)>", r'<html\1 data-dih="">', html, count=1, flags=re.I)

    body_open = re.search(r"<body[^>]*>", html, re.I)
    html = html[: body_open.end()] + "\n" + header_html() + html[body_open.end():]

    tail = explore_html(kind) + "\n" + footer_html() + "\n" + script_tag() + "\n"
    idx = html.rfind("</body>")
    if idx == -1:
        return html
    return html[:idx] + tail + html[idx:]


def process(path: Path) -> bool:
    rel = path.relative_to(ROOT)
    html = path.read_text(encoding="utf-8")
    meta = choose_meta(rel, html)
    updated = update_body(update_head(html, rel, meta), rel, meta)
    if updated != html:
        path.write_text(updated, encoding="utf-8")
        return True
    return False


def targets():
    if len(sys.argv) > 1:
        return [ROOT / a for a in sys.argv[1:]]
    pages = []
    for p in sorted(ROOT.glob("*.html")):
        if p.name in GENERATED or p.name == "index.html":
            continue
        pages.append(p)
    pages += sorted((ROOT / "software").glob("*.html"))
    pages += sorted((ROOT / "post").glob("*.html"))
    return pages


if __name__ == "__main__":
    changed = 0
    for path in targets():
        if path.exists() and process(path):
            print("updated", path.relative_to(ROOT))
            changed += 1
    print(f"{changed} page(s) updated")

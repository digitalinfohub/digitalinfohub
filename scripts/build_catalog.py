#!/usr/bin/env python3
"""Build assets/catalog.js — the full page index used by the Hub Guide,
the terminal (ls / find / ask) and the interest board.

Every URL in sitemap.xml that resolves to a local file is included, so the
catalog always covers every available page.

Usage:
  python3 scripts/build_catalog.py
"""
import re
import sys
from html import unescape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITEMAP = ROOT / "sitemap.xml"
OUT = ROOT / "assets" / "catalog.js"

TOPIC_FILES = {
    "artificialintelligence", "machinelearning", "blockchain", "cloudcomputing",
    "cybersecurity", "internetofthings", "quantumcomputing", "bigdata",
    "virtualreality", "5gnetworks", "apis", "devops", "opensource", "robotics",
    "edgecomputing", "web3", "semiconductors", "3dprinting", "biotechnology",
    "greentechnology", "digitaltwins", "zerotrustsecurity", "serverlesscomputing",
    "neuromorphiccomputing", "augmentedreality", "drones", "nanotechnology",
    "spacetechnology", "wearabletechnology", "smartcities", "humanoidrobots",
    "autonomousvehicles", "datacenters",
}

GAME_SLUGS = {
    "snake", "2048", "pong", "memory", "mole", "reaction", "simon",
    "tictactoe", "typing",
}


def page_file(url_path: str):
    if url_path in ("", "/"):
        return ROOT / "index.html"
    clean = url_path.strip("/")
    for candidate in (ROOT / (clean + ".html"), ROOT / clean / "index.html"):
        if candidate.exists():
            return candidate
    return None


def meta(html: str, name: str):
    m = re.search(
        r'<meta[^>]+(?:name|property)=["\']' + re.escape(name) + r'["\'][^>]*content=["\']([^"\']*)',
        html, re.I,
    )
    if not m:
        m = re.search(
            r'<meta[^>]+content=["\']([^"\']*)["\'][^>]*(?:name|property)=["\']' + re.escape(name) + r'["\']',
            html, re.I,
        )
    return unescape(m.group(1)).strip() if m else ""


def title_of(html: str):
    m = re.search(r"<title>(.*?)</title>", html, re.S | re.I)
    if not m:
        return ""
    return re.sub(r"\s+", " ", unescape(m.group(1))).strip()


def category(url_path: str, html: str):
    p = url_path.rstrip("/") or "/"
    if p == "/":
        return "home"
    if p == "/software":
        return "software"
    if p.startswith("/software/"):
        return "japanese" if 'lang="ja"' in html[:400] or "lang=\"ja\"" in html[:2000] else "app"
    if p == "/games":
        return "games"
    if p.startswith("/games/"):
        return "game"
    if p.startswith("/post/"):
        return "blog"
    if p in ("/news", "/offline"):
        return "news"
    if p == "/coincompass":
        return "markets"
    if p == "/quiz":
        return "quiz"
    if p == "/techproducts":
        return "products"
    if p == "/terminal":
        return "terminal"
    slug = p.strip("/")
    if slug in TOPIC_FILES:
        return "guide"
    if p in ("/about", "/services", "/advertise", "/privacy-policy", "/contact", "/subscribe"):
        return "about"
    return "page"


def main():
    if not SITEMAP.exists():
        sys.exit("sitemap.xml missing")
    xml = SITEMAP.read_text(encoding="utf-8")
    urls = re.findall(r"<loc>\s*([^<\s]+)\s*</loc>", xml)
    rows = []
    seen = set()
    for url in urls:
        path = re.sub(r"^https?://[^/]+", "", url) or "/"
        path = path.split("?")[0].split("#")[0]
        if not path.startswith("/"):
            path = "/" + path
        if path in seen:
            continue
        f = page_file(path)
        if not f:
            continue
        html = f.read_text(encoding="utf-8", errors="ignore")
        title = title_of(html)
        if not title:
            continue
        seen.add(path)
        rows.append({
            "path": path,
            "title": title,
            "desc": meta(html, "description")[:220],
            "kw": meta(html, "keywords")[:160],
            "cat": category(path, html),
            "file": str(f.relative_to(ROOT)),
        })
    rows.sort(key=lambda r: (r["cat"], r["path"]))
    payload = ",\n".join(
        "{" + ",".join([
            'path:%s' % _js(r["path"]),
            'title:%s' % _js(r["title"]),
            'desc:%s' % _js(r["desc"]),
            'kw:%s' % _js(r["kw"]),
            'cat:%s' % _js(r["cat"]),
        ]) + "}"
        for r in rows
    )
    OUT.write_text(
        "/* Generated by scripts/build_catalog.py — do not edit by hand. */\n"
        "window.DIH_CATALOG=[\n" + payload + "\n];\n",
        encoding="utf-8",
    )
    print(f"catalog: {len(rows)} pages -> {OUT.relative_to(ROOT)}")
    missing = [u for u in urls if re.sub(r'^https?://[^/]+', '', u).split('#')[0] not in seen]
    if missing:
        print("skipped (no local file):", *missing[:12], sep="\n  ")


def _js(value: str):
    return '"' + (
        value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
    ) + '"'


if __name__ == "__main__":
    main()
